import * as Lucide from 'lucide-react';
import {forwardRef} from 'react';
import type {LucideProps} from 'lucide-react';
const linear=new Set(['Search','RefreshCw','ArrowLeft','ArrowRight','ArrowUp','Bold','Italic','Check','CheckCheck','ChevronDown','ChevronLeft','ChevronRight','List','LoaderCircle','MoreHorizontal','Plus','Send','Undo2','X','Link','Scissors']);
function glyph(name:keyof typeof Lucide){
 const Base=Lucide[name] as React.ForwardRefExoticComponent<LucideProps>;
 const Icon=forwardRef<SVGSVGElement,LucideProps>((props,ref)=><Base ref={ref} strokeWidth={1.7} fill={linear.has(name)?'none':'currentColor'} fillOpacity={.18} {...props}/>);
 Icon.displayName='Tone'+name;return Icon;
}
